"""Can moves reach this arrangement? A membership test for any puzzle given as permutations of positions.

The moves of a puzzle permute its sticker positions; they generate a group G. An arrangement is
reachable exactly when some element of G sends every sticker's home position to where the sticker
is now. Only the stickers' positions are known (the other positions are empty and interchangeable),
so the test sifts a *partial* map through a stabiliser chain whose base lies among the home
positions: at each level the image of the base point picks the coset representative, and an
arrangement is reachable when the sift ends in the identity on every known point.

The chain (Schreier-Sims, from sympy) is built once and cached in data/cache.
"""
from __future__ import annotations

import hashlib
import math
import pickle
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

import numpy as np

from scanner.paths import DATA


@dataclass
class StabiliserChain:
    n: int
    base: list[int]
    #: transversal[i][beta] = an element (as an image array) that sends base[i] to beta, fixing base[:i]
    transversal: list[dict[int, np.ndarray]]

    @property
    def order(self) -> int:
        return math.prod(len(t) for t in self.transversal)

    def sift(self, points: np.ndarray, images: np.ndarray) -> np.ndarray | None:
        """If some group element sends points[j] to images[j] for every j, that element (as an image array
        of all n points); otherwise None. Every base point must be among ``points``."""
        points = np.asarray(points, dtype=np.int64)
        h = np.asarray(images, dtype=np.int64).copy()
        where = {int(p): j for j, p in enumerate(points)}
        used = []
        for b, t in zip(self.base, self.transversal):
            j = where.get(b)
            if j is None:
                raise ValueError(f"base point {b} is not among the known points")
            u = t.get(int(h[j]))
            if u is None:
                return None
            used.append(u)
            u_inv = np.empty_like(u)
            u_inv[u] = np.arange(self.n, dtype=u.dtype)
            h = u_inv[h]                            # h <- u^-1 after h
        if not np.array_equal(h, points):
            return None
        g = np.arange(self.n)                       # the element: u_0 after u_1 after ... after u_k
        for u in reversed(used):
            g = u[g]
        return g

    def contains(self, points: Sequence[int], images: Sequence[int]) -> bool:
        return self.sift(np.asarray(points), np.asarray(images)) is not None


def _key(generators: Sequence[np.ndarray], base: Sequence[int]) -> str:
    h = hashlib.sha1()
    for g in generators:
        h.update(np.asarray(g, dtype=np.int32).tobytes())
    h.update(np.asarray(base, dtype=np.int32).tobytes())
    return h.hexdigest()[:16]


def build_chain(generators: Sequence[np.ndarray], base_points: Sequence[int], cache: Path | None = None) -> StabiliserChain:
    """The stabiliser chain of the group generated by ``generators`` (image arrays on n points), with a
    base taken from ``base_points`` (in that order). Raises if the base cannot stay within them."""
    n = len(generators[0])
    cache = cache if cache is not None else DATA / "cache"
    path = cache / f"chain-{_key(generators, base_points)}.pkl"
    if path.exists():
        with path.open("rb") as f:
            return pickle.load(f)

    from sympy.combinatorics import Permutation, PermutationGroup
    from sympy.combinatorics.util import _distribute_gens_by_base, _orbits_transversals_from_bsgs

    group = PermutationGroup([Permutation(list(map(int, g))) for g in generators])
    base, strong = group.schreier_sims_incremental(base=[int(b) for b in base_points])
    allowed = set(int(b) for b in base_points)
    # Drop base points whose level is trivial; the rest must be known points.
    distr = _distribute_gens_by_base(base, strong)
    _, transversals = _orbits_transversals_from_bsgs(base, distr, transversals_only=False)
    levels = [(b, t) for b, t in zip(base, transversals) if len(t) > 1]
    bad = [b for b, _ in levels if b not in allowed]
    if bad:
        raise ValueError(f"the group is not determined by the given points (base needs {bad})")
    chain = StabiliserChain(
        n=n,
        base=[int(b) for b, _ in levels],
        transversal=[{int(beta): np.array(u.array_form, dtype=np.int16) for beta, u in t.items()} for _, t in levels],
    )
    # Check the convention: transversal[i][beta] sends base[i] to beta.
    for b, t in zip(chain.base, chain.transversal):
        for beta, u in t.items():
            if int(u[b]) != beta:
                raise AssertionError("unexpected transversal convention")
    cache.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    with tmp.open("wb") as f:
        pickle.dump(chain, f)
    tmp.replace(path)
    return chain
